void ctr_draw_text(uint32_t *image, unsigned w, unsigned h, unsigned x,
                   unsigned y, const char *text, uint32_t color) {
    if (!image || !text) return;
    for (; *text && x < w; ++text, x += 6) {
        char c = *text >= 'a' && *text <= 'z' ? (char)(*text - 'a' + 'A') : *text;
        const Glyph *glyph = &glyphs[sizeof(glyphs)/sizeof(glyphs[0]) - 2];
        for (size_t i=0; i<sizeof(glyphs)/sizeof(glyphs[0]); ++i)
            if (glyphs[i].symbol == c) { glyph=&glyphs[i]; break; }
        for (unsigned dy=0; dy<7 && y+dy<h; ++dy)
            for (unsigned dx=0; dx<5 && x+dx<w; ++dx)
                if (glyph->row[dy] & (1u << (4-dx))) image[(y+dy)*w+x+dx]=color;
    }
}
